# Words across writing systems

This fixture checks font coverage, Unicode preservation, text shaping, and logical reading order. A visually plausible page alone does not establish that all four are correct.

## Latin, accents, and symbols

English: The quick brown fox jumps over the lazy dog.

French: L'été à Montréal est agréable. Élève, façade, cœur.

Greek: Η γνώση αρχίζει με την περιέργεια.

## Right-to-left text

Arabic: المعرفة تبدأ بالسؤال.

Hebrew: ידע מתחיל בשאלה.

## East Asian writing

Korean: 새로운 문서 언어는 읽기 쉽고 빠르게 처리되어야 합니다.

Japanese: 文書は読みやすく、正確に表示される必要があります。

Chinese: 文档应当清晰易读，并在不同输出中保持一致。

## Mathematics remains part of the text

The identity $e^{i\pi} + 1 = 0$ combines Latin and Greek symbols with mathematical operators.
